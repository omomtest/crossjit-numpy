def c_bytes(name: str, data: bytes) -> list[str]:
    lines = [f"static const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 8):
        row = ", ".join(f"0x{byte:02x}" for byte in data[i : i + 8])
        lines.append(f"    {row},")
    lines.append("};")
    return lines


