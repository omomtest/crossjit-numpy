            "      PYJIT_EXT_STENCIL_VALUE_RECORD_EXT_HIT, 0, 0 },",
            "    { 177, PYJIT_EXT_STENCIL_SECTION_CODE, PYJIT_EXT_STENCIL_PATCH_ABS64,",
            "      PYJIT_EXT_STENCIL_VALUE_RECORD_EXT_MISS, 0, 0 },",
            "    { 213, PYJIT_EXT_STENCIL_SECTION_CODE, PYJIT_EXT_STENCIL_PATCH_REL32,",
